// Generates supabase/migrations/..._seed.sql from the same demo data the
// frontend uses, so Demo Mode and Supabase Mode start identical.
// Usage: npm run seed:generate
import { writeFileSync } from 'node:fs'
import { buildSeed, TABLES } from '../src/data/demoData.js'

const NOW = Date.UTC(2026, 0, 1)
const seed = buildSeed(NOW)

const lit = (v) => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number' || typeof v === 'boolean') return String(v)
  if (typeof v === 'string' && /^\d{4}-\d\d-\d\dT[\d:.]+Z$/.test(v)) {
    const secs = Math.round((NOW - Date.parse(v)) / 1000)
    return secs >= 0 ? `now() - interval '${secs} seconds'` : `now() + interval '${-secs} seconds'`
  }
  return `'${String(v).replace(/'/g, "''")}'`
}

const inserts = TABLES.map((t) => {
  const rows = seed[t]
  const cols = Object.keys(rows[0])
  const values = rows.map((r) => `    (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n')
  return `  insert into public.${t} (${cols.join(', ')}) values\n${values};`
}).join('\n\n')

const sql = `-- GENERATED by scripts/generate-seed.mjs — do not edit by hand.
-- Fictional demo data. Timestamps are relative to now() at seed time.

create or replace function public.seed_demo_data() returns void
language plpgsql security definer set search_path = public as $fn$
begin
${inserts}
end $fn$;

-- DEMO ONLY: lets the "Reset Demo" button restore seed data with the anon key.
-- Drop this function (or revoke anon execute) before any real deployment.
create or replace function public.reset_demo() returns void
language plpgsql security definer set search_path = public as $fn$
begin
  delete from public.notifications where true;
  delete from public.incident_notes where true;
  delete from public.incidents where true;
  delete from public.journey_updates where true;
  delete from public.journeys where true;
  delete from public.scam_reports where true;
  delete from public.drivers where true;
  delete from public.hotels where true;
  perform public.seed_demo_data();
end $fn$;

revoke all on function public.seed_demo_data() from public, anon, authenticated;
revoke all on function public.reset_demo() from public;
grant execute on function public.reset_demo() to anon, authenticated;

select public.seed_demo_data();
`

writeFileSync(new URL('../supabase/migrations/20261123000003_seed.sql', import.meta.url), sql)
console.log('Wrote supabase/migrations/20261123000003_seed.sql')
